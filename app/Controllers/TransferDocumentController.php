<?php

namespace App\Controllers;

use App\Helpers\AuthHelper;
use App\Core\Database;
use PDO;

class TransferDocumentController {
    public function __construct() {
        AuthHelper::requireRole(['SUPERADMIN', 'ADMIN']);
    }

    public function index() {
        $id = (int)($_GET['id'] ?? 0);
        $versionNo = max(0, (int)($_GET['version'] ?? 0));
        if ($id <= 0) {
            $_SESSION['error'] = 'Transfer tidak valid.';
            header('Location: ' . url('/transfers'));
            exit;
        }

        $pdo = Database::getInstance()->getConnection();
        $stmt = $pdo->prepare("SELECT t.*, sw.name AS source_warehouse, dw.name AS dest_warehouse, u.name AS sender_name,
                r.receiver_name AS latest_receiver_name, r.receiver_role AS latest_receiver_role,
                r.receiver_phone AS latest_receiver_phone, r.received_at AS latest_received_at,
                r.notes AS latest_receiver_notes
            FROM transfers t
            JOIN warehouses sw ON sw.id = t.source_warehouse_id
            JOIN warehouses dw ON dw.id = t.destination_warehouse_id
            JOIN users u ON u.id = t.sent_by
            LEFT JOIN transfer_receipts r ON r.id = (
                SELECT tr2.id FROM transfer_receipts tr2
                WHERE tr2.transfer_id = t.id
                ORDER BY tr2.id DESC LIMIT 1
            )
            WHERE t.id = ?");
        $stmt->execute([$id]);
        $transfer = $stmt->fetch(PDO::FETCH_ASSOC);
        if (!$transfer) {
            $_SESSION['error'] = 'Transfer tidak ditemukan.';
            header('Location: ' . url('/transfers'));
            exit;
        }

        // Receipt identity belongs to transfer_receipts. Prefer the latest receipt
        // over legacy nullable fields on transfers for the transfer-level fallback.
        if ($transfer['latest_receiver_name'] !== null) {
            $transfer['receiver_name'] = $transfer['latest_receiver_name'];
            $transfer['receiver_role'] = $transfer['latest_receiver_role'];
            $transfer['receiver_phone'] = $transfer['latest_receiver_phone'];
            $transfer['received_at'] = $transfer['latest_received_at'];
            $transfer['receiver_notes'] = $transfer['latest_receiver_notes'];
        }

        // Keep the database version history append-only, but build missing versions
        // from the exact receipt event instead of the current/latest receipt state.
        $this->ensureSnapshot($pdo, $transfer, $id);

        $versionStmt = $pdo->prepare('SELECT * FROM transfer_surat_jalan_versions WHERE transfer_id = ? ORDER BY version_no DESC');
        $versionStmt->execute([$id]);
        $versions = $versionStmt->fetchAll(PDO::FETCH_ASSOC);

        if (!$versions) {
            $_SESSION['error'] = 'Belum ada Surat Jalan untuk transfer ini.';
            header('Location: ' . url('/transfers/show?id=' . $id));
            exit;
        }

        // Normalize the documents in memory from immutable receipt snapshots. This
        // repairs old versions that were generated by the previous "latest receipt"
        // logic without rewriting historical rows automatically.
        $receipts = $this->getReceiptEvents($pdo, $id);
        foreach ($versions as &$version) {
            $version = $this->normalizeVersion($pdo, $version, $transfer, $receipts, $id);
        }
        unset($version);

        $selectedVersion = null;
        if ($versionNo > 0) {
            foreach ($versions as $version) {
                if ((int)$version['version_no'] === $versionNo) {
                    $selectedVersion = $version;
                    break;
                }
            }
        }
        if (!$selectedVersion) {
            $selectedVersion = $versions[0];
        }

        require __DIR__ . '/../../resources/views/transactions/transfers/documents.php';
    }

    private function getReceiptEvents(PDO $pdo, int $transferId): array {
        $stmt = $pdo->prepare("SELECT id, receiver_name, receiver_role, receiver_phone, received_at, notes, created_at
            FROM transfer_receipts
            WHERE transfer_id = ?
            ORDER BY id ASC");
        $stmt->execute([$transferId]);
        return $stmt->fetchAll(PDO::FETCH_ASSOC);
    }

    private function normalizeVersion(PDO $pdo, array $version, array $transfer, array $receipts, int $transferId): array {
        $versionNo = (int)($version['version_no'] ?? 0);
        $baseCode = trim((string)($transfer['transaction_code'] ?? ''));
        if ($baseCode === '' || $baseCode === 'SJ-') {
            $baseCode = 'TRF-' . str_pad((string)$transferId, 6, '0', STR_PAD_LEFT);
        }

        $expectedDocumentNo = 'SJ-' . $baseCode . '-' . str_pad((string)max(1, $versionNo), 2, '0', STR_PAD_LEFT);
        $storedDocumentNo = trim((string)($version['document_no'] ?? ''));
        if ($storedDocumentNo === '' || $storedDocumentNo === 'SJ-' || $storedDocumentNo === 'SJ--01') {
            $version['document_no'] = $expectedDocumentNo;
        }

        if ($versionNo <= 1) {
            $version['receiver_name'] = null;
            $version['receiver_role'] = null;
            $version['receiver_phone'] = null;
            $version['received_at'] = null;
            $version['event_label'] = 'Pengiriman Awal';
            $version['items_json'] = json_encode($this->buildInitialItems($pdo, $transferId), JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES);
            return $version;
        }

        $receiptIndex = $versionNo - 2;
        if (!isset($receipts[$receiptIndex])) {
            // No matching receipt yet. Keep the stored snapshot rather than inventing
            // a receiver or receipt date.
            return $version;
        }

        $receipt = $receipts[$receiptIndex];
        $version['event_label'] = 'Pembaruan Penerimaan #' . ($receiptIndex + 1);
        $version['receiver_name'] = $receipt['receiver_name'] ?? null;
        $version['receiver_role'] = $receipt['receiver_role'] ?? null;
        $version['receiver_phone'] = $receipt['receiver_phone'] ?? null;
        $version['received_at'] = $receipt['received_at'] ?? null;
        if (trim((string)($receipt['notes'] ?? '')) !== '') {
            $version['notes'] = $receipt['notes'];
        }
        $version['items_json'] = json_encode($this->buildReceiptItems($pdo, $transferId, (int)$receipt['id']), JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES);

        return $version;
    }

    private function buildInitialItems(PDO $pdo, int $transferId): array {
        $itemsStmt = $pdo->prepare("SELECT ti.id, ti.quantity_sent, m.kode_barang, m.nama, m.is_serialized
            FROM transfer_items ti
            JOIN master_items m ON m.id = ti.master_item_id
            WHERE ti.transfer_id = ?
            ORDER BY ti.id ASC");
        $itemsStmt->execute([$transferId]);
        $items = $itemsStmt->fetchAll(PDO::FETCH_ASSOC);

        $serialStmt = $pdo->prepare("SELECT tis.transfer_item_id, sn.serial_number
            FROM transfer_item_serials tis
            JOIN serial_numbers sn ON sn.id = tis.serial_number_id
            WHERE tis.transfer_item_id IN (SELECT id FROM transfer_items WHERE transfer_id = ?)
            ORDER BY tis.id ASC");
        $serialStmt->execute([$transferId]);
        $serialMap = [];
        foreach ($serialStmt->fetchAll(PDO::FETCH_ASSOC) as $sn) {
            $serialMap[(int)$sn['transfer_item_id']][] = [
                'serial_number' => $sn['serial_number'],
                'status' => 'IN_TRANSIT',
            ];
        }

        $result = [];
        foreach ($items as $item) {
            $result[] = [
                'kode_barang' => $item['kode_barang'],
                'nama' => $item['nama'],
                'is_serialized' => (int)$item['is_serialized'],
                'quantity_sent' => (int)$item['quantity_sent'],
                'quantity_received' => 0,
                'serial_numbers' => $serialMap[(int)$item['id']] ?? [],
            ];
        }
        return $result;
    }

    private function buildReceiptItems(PDO $pdo, int $transferId, int $receiptId): array {
        $stmt = $pdo->prepare("SELECT ti.id, ti.quantity_sent, m.kode_barang, m.nama, m.is_serialized,
                s.cumulative_quantity, s.serial_numbers_json
            FROM transfer_items ti
            JOIN master_items m ON m.id = ti.master_item_id
            LEFT JOIN transfer_receipt_item_snapshots s
                ON s.transfer_item_id = ti.id AND s.receipt_id = ?
            WHERE ti.transfer_id = ?
            ORDER BY ti.id ASC");
        $stmt->execute([$receiptId, $transferId]);
        $rows = $stmt->fetchAll(PDO::FETCH_ASSOC);

        $result = [];
        foreach ($rows as $row) {
            $serials = [];
            if (!empty($row['serial_numbers_json'])) {
                $decoded = json_decode($row['serial_numbers_json'], true);
                if (is_array($decoded)) {
                    foreach ($decoded as $serial) {
                        if (is_string($serial)) {
                            $serials[] = ['serial_number' => $serial, 'status' => 'RECEIVED'];
                        } elseif (is_array($serial) && isset($serial['serial_number'])) {
                            $serials[] = [
                                'serial_number' => (string)$serial['serial_number'],
                                'status' => $serial['status'] ?? 'RECEIVED',
                            ];
                        }
                    }
                }
            }

            $result[] = [
                'kode_barang' => $row['kode_barang'],
                'nama' => $row['nama'],
                'is_serialized' => (int)$row['is_serialized'],
                'quantity_sent' => (int)$row['quantity_sent'],
                'quantity_received' => (int)($row['cumulative_quantity'] ?? 0),
                'serial_numbers' => $serials,
            ];
        }

        return $result;
    }

    private function ensureSnapshot(PDO $pdo, array $transfer, int $transferId): void {
        $receiptCountStmt = $pdo->prepare('SELECT COUNT(*) FROM transfer_receipts WHERE transfer_id = ?');
        $receiptCountStmt->execute([$transferId]);
        $receiptCount = (int)$receiptCountStmt->fetchColumn();
        $targetVersion = 1 + $receiptCount;

        $lastStmt = $pdo->prepare('SELECT version_no FROM transfer_surat_jalan_versions WHERE transfer_id = ? ORDER BY version_no DESC LIMIT 1');
        $lastStmt->execute([$transferId]);
        $lastVersion = (int)($lastStmt->fetchColumn() ?? 0);

        if ($lastVersion >= $targetVersion) {
            return;
        }

        $receipts = $this->getReceiptEvents($pdo, $transferId);
        $baseCode = trim((string)($transfer['transaction_code'] ?? ''));
        if ($baseCode === '') {
            $baseCode = 'TRF-' . str_pad((string)$transferId, 6, '0', STR_PAD_LEFT);
        }

        for ($versionNo = $lastVersion + 1; $versionNo <= $targetVersion; $versionNo++) {
            $receipt = null;
            if ($versionNo === 1) {
                $eventLabel = 'Pengiriman Awal';
                $receiverName = null;
                $receiverRole = null;
                $receiverPhone = null;
                $receivedAt = null;
                $items = $this->buildInitialItems($pdo, $transferId);
            } else {
                $receiptIndex = $versionNo - 2;
                if (!isset($receipts[$receiptIndex])) {
                    continue;
                }
                $receipt = $receipts[$receiptIndex];
                $eventLabel = 'Pembaruan Penerimaan #' . ($receiptIndex + 1);
                $receiverName = $receipt['receiver_name'] ?? null;
                $receiverRole = $receipt['receiver_role'] ?? null;
                $receiverPhone = $receipt['receiver_phone'] ?? null;
                $receivedAt = $receipt['received_at'] ?? null;
                $items = $this->buildReceiptItems($pdo, $transferId, (int)$receipt['id']);
            }

            $documentNo = 'SJ-' . $baseCode . '-' . str_pad((string)$versionNo, 2, '0', STR_PAD_LEFT);
            $createdBy = (int)(AuthHelper::user()['id'] ?? 0);

            $insert = $pdo->prepare("INSERT IGNORE INTO transfer_surat_jalan_versions
                (transfer_id, version_no, document_no, document_type, event_label, created_by, sent_at, received_at,
                 sender_name, driver_name, driver_phone, vehicle_number, receiver_name, receiver_role, receiver_phone,
                 source_warehouse, destination_warehouse, notes, items_json)
                VALUES (?, ?, ?, 'TRANSFER', ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)");
            $insert->execute([
                $transferId,
                $versionNo,
                $documentNo,
                $eventLabel,
                $createdBy > 0 ? $createdBy : null,
                $transfer['sent_at'] ?? null,
                $receivedAt,
                $transfer['sender_name'] ?? null,
                $transfer['driver_name'] ?? null,
                $transfer['driver_phone'] ?? null,
                $transfer['vehicle_number'] ?? null,
                $receiverName,
                $receiverRole,
                $receiverPhone,
                $transfer['source_warehouse'] ?? null,
                $transfer['destination_warehouse'] ?? null,
                $versionNo > 1 && $receipt !== null ? ($receipt['notes'] ?? null) : ($transfer['notes'] ?? null),
                json_encode($items, JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES)
            ]);
        }
    }
}
